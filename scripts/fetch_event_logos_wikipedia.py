"""Fetch WWE event logos via Wikipedia Special:FilePath + REST summary."""

from __future__ import annotations

import json
import re
import time
from pathlib import Path
from typing import Any
from urllib.parse import quote, unquote, urlparse

import pandas as pd
import requests

from wiki_series_titles import KNOWN_FILES, SERIES_TITLES

ROOT = Path(__file__).resolve().parents[1]
OUT_DIR = ROOT / "frontend" / "public" / "events"
GENERATED_TS = ROOT / "frontend" / "src" / "assets" / "eventLogoManifest.generated.ts"
MART = ROOT / "data" / "warehouse" / "marts" / "mart_event_analytics.csv"

UA = "WWE-PLE-Analytics/1.3 (educational; local analytics dashboard)"
S = requests.Session()
S.headers.update({"User-Agent": UA})

FILEPATH = "https://en.wikipedia.org/wiki/Special:FilePath/"
REST = "https://en.wikipedia.org/api/rest_v1/page/summary/"


def slugify(series: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", series.lower()).strip("-") or "event"


def existing(slug: str) -> Path | None:
    for e in (".png", ".svg", ".jpg", ".webp"):
        p = OUT_DIR / f"{slug}{e}"
        if p.exists() and p.stat().st_size > 300:
            return p
    return None


def ext_of(name: str, url: str = "") -> str:
    for cand in (name, urlparse(url).path):
        low = unquote(cand).lower()
        for e in (".svg", ".png", ".jpg", ".jpeg", ".webp"):
            if low.endswith(e):
                return ".jpg" if e == ".jpeg" else e
        if "svg.png" in low:
            return ".png"
    return ".png"


def download(url: str, dest: Path) -> bool:
    for attempt in range(6):
        try:
            r = S.get(url, timeout=60, allow_redirects=True)
            if r.status_code == 429:
                wait = 10 + attempt * 10
                print(f"    429 → {wait}s")
                time.sleep(wait)
                continue
            if r.status_code >= 400:
                return False
            ctype = (r.headers.get("Content-Type") or "").lower()
            if "text/html" in ctype:
                return False
            dest.parent.mkdir(parents=True, exist_ok=True)
            dest.write_bytes(r.content)
            return dest.stat().st_size > 300
        except Exception as exc:  # noqa: BLE001
            print(f"    err {exc}")
            time.sleep(3 + attempt)
    return False


def try_files(series: str, slug: str) -> dict[str, Any] | None:
    for fname in KNOWN_FILES.get(series, []):
        url = FILEPATH + quote(fname)
        dest = OUT_DIR / f"{slug}{ext_of(fname)}"
        print(f"  file {fname}")
        if download(url, dest):
            return {
                "source": url,
                "file_title": f"File:{fname}",
                "local_path": f"/events/{dest.name}",
                "method": "special_filepath",
            }
        time.sleep(1.5)
    return None


def try_rest(series: str, slug: str) -> dict[str, Any] | None:
    for title in SERIES_TITLES.get(series, [series.replace(" ", "_")]):
        print(f"  rest {title}")
        for attempt in range(5):
            r = S.get(REST + title, timeout=40)
            if r.status_code == 429:
                wait = 12 + attempt * 10
                print(f"    429 → {wait}s")
                time.sleep(wait)
                continue
            if r.status_code == 404:
                break
            if r.status_code >= 400:
                time.sleep(2)
                break
            data = r.json()
            src = (data.get("originalimage") or data.get("thumbnail") or {}).get("source")
            if not src:
                break
            name = unquote(urlparse(src).path.split("/")[-1])
            dest = OUT_DIR / f"{slug}{ext_of(name, src)}"
            clean = src.split("?")[0]
            if download(clean, dest) or download(src, dest):
                return {
                    "source": src,
                    "page_title": data.get("title"),
                    "pageimage": name,
                    "local_path": f"/events/{dest.name}",
                    "method": "rest_summary",
                }
            break
        time.sleep(2.5)
    return None


def write_ts(entries: list[dict[str, Any]]) -> None:
    lines = [
        "/* Auto-generated by scripts/fetch_event_logos_wikipedia.py */",
        "export type EventLogoEntry = { series: string; slug: string; path: string; sourceUrl?: string; wikiTitle?: string; method?: string };",
        "export const EVENT_LOGOS: Record<string, EventLogoEntry> = {",
    ]
    for e in sorted((x for x in entries if x.get("local_path")), key=lambda x: x["slug"]):
        lines.append(
            "  "
            + json.dumps(e["slug"])
            + ": "
            + json.dumps(
                {
                    "series": e["series"],
                    "slug": e["slug"],
                    "path": e["local_path"],
                    "sourceUrl": e.get("source"),
                    "wikiTitle": e.get("page_title") or e.get("file_title"),
                    "method": e.get("method"),
                },
                ensure_ascii=False,
            )
            + ","
        )
    lines.append("};")
    lines.append("export const EVENT_LOGO_BY_SERIES: Record<string, string> = {")
    for e in sorted((x for x in entries if x.get("local_path")), key=lambda x: x["series"]):
        lines.append(f"  {json.dumps(e['series'])}: {json.dumps(e['local_path'])},")
    lines.append("};")
    GENERATED_TS.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> None:
    import sys

    sys.path.insert(0, str(Path(__file__).resolve().parent))
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    series_list = sorted({str(s) for s in pd.read_csv(MART)["event_series"].dropna().unique()})
    print(f"{len(series_list)} series")
    results: list[dict[str, Any]] = []
    ok = 0
    for i, series in enumerate(series_list, 1):
        slug = slugify(series)
        print(f"[{i}/{len(series_list)}] {series}")
        entry: dict[str, Any] = {"series": series, "slug": slug}
        cached = existing(slug)
        if cached:
            print(f"  cached {cached.name}")
            entry["local_path"] = f"/events/{cached.name}"
            entry["method"] = "cached"
            results.append(entry)
            ok += 1
            continue
        hit = try_files(series, slug) or try_rest(series, slug)
        if hit:
            entry.update(hit)
            print(f"  OK {hit['local_path']}")
            ok += 1
        else:
            print("  MISSING")
        results.append(entry)
        time.sleep(3.0)

    (OUT_DIR / "manifest.json").write_text(
        json.dumps(
            {
                "source": "English Wikipedia Special:FilePath + REST summary",
                "count_ok": ok,
                "count_total": len(series_list),
                "items": results,
            },
            indent=2,
        ),
        encoding="utf-8",
    )
    write_ts(results)
    print(f"Done {ok}/{len(series_list)}")
    missing = [e["series"] for e in results if not e.get("local_path")]
    if missing:
        print("Missing:", ", ".join(missing))


if __name__ == "__main__":
    main()
